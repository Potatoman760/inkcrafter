import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Generate ordinary imports so the same pure data modules work in Vite and
// the standalone Node exporter. No hand-maintained list of kinds or parsers.
const directory = join(dirname(fileURLToPath(import.meta.url)), '../src/shared/bundle/minigame')
const entries = (await readdir(directory, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
const modules = []
for (const name of entries) {
  if (!/^[a-z][a-z0-9_-]*$/.test(name)) throw new Error(`Invalid minigame folder: ${name}`)
  try { await readFile(join(directory, name, 'data.ts')) } catch (error) {
    if (error.code === 'ENOENT') continue
    throw error
  }
  modules.push(name)
}
const source = '// Generated by scripts/sync-minigames.mjs; add a <kind>/data.ts module to register a kind.\n' +
  modules.map((name, index) => `import module${index} from './${name}/data'\nexport * from './${name}/data'`).join('\n') +
  `\n\nconst modules = [${modules.map((_, index) => `module${index}`).join(', ')}] as const\n` +
  `export type MinigameDefinition = ReturnType<(typeof modules)[number]['create']>\n` +
  `export const minigameModules = new Map<string, (typeof modules)[number]>()\n` +
  `for (const module of modules) {\n` +
  `  if (minigameModules.has(module.kind)) throw new Error(\`Duplicate minigame kind: \${module.kind}\`)\n` +
  `  minigameModules.set(module.kind, module)\n}\n`
const target = join(directory, 'registry.generated.ts')
const current = await readFile(target, 'utf8').catch((error) => {
  if (error.code === 'ENOENT') return null
  throw error
})
if (process.argv.includes('--check')) {
  if (current !== source) throw new Error('Minigame registry is stale. Run npm run minigames:sync in Editor.')
} else if (current !== source) {
  await writeFile(target, source)
}

const checks = []
for (const name of modules) {
  try { await readFile(join(directory, name, 'check.editor.ts')) } catch (error) {
    if (error.code === 'ENOENT') continue
    throw error
  }
  checks.push(name)
}
const checkSource = '// Generated by scripts/sync-minigames.mjs.\n' +
  "import type { MinigameCheck } from './check.editor'\n" +
  checks.map((name, index) => `import check${index} from './${name}/check.editor'`).join('\n') +
  `\n\nexport const minigameChecks = new Map<string, MinigameCheck>([\n` +
  checks.map((name, index) => `  ['${name}', check${index}],`).join('\n') + '\n])\n'
const checkTarget = join(directory, 'checks.editor.ts')
const existingChecks = await readFile(checkTarget, 'utf8').catch((error) => {
  if (error.code === 'ENOENT') return null
  throw error
})
if (process.argv.includes('--check')) {
  if (existingChecks !== checkSource) throw new Error('Minigame checks are stale. Run npm run minigames:sync in Editor.')
} else if (existingChecks !== checkSource) await writeFile(checkTarget, checkSource)
